using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;

namespace Configurables;

[Generator(LanguageNames.CSharp)]
public partial class ConfigurablesGenerator : IIncrementalGenerator
{
    private record Target
    {
        public INamedTypeSymbol ClassSymbol { get; set; }
        public IEnumerable<ISymbol> ConfigurableMembers { get; set; }

        public Target(INamedTypeSymbol classSymbol, IEnumerable<ISymbol> configurables)
        {
            ClassSymbol = classSymbol;
            ConfigurableMembers = configurables;
        }
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static context =>
        {
            context.AddSource("ConfigurableAttribute.cs", """
                              using System;

                              namespace Configurables
                              {
                                  [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property, AllowMultiple = false, Inherited = false)]
                                  public sealed class ConfigurableAttribute : Attribute
                                  {
                                      public ConfigurableAttribute() {}
                                  }
                              }


                              """);
        });

        var source = context.SyntaxProvider.ForAttributeWithMetadataName(
            // target Attribute name
            "Configurables.ConfigurableAttribute",
            static (node, token) => true,
            static (context, token) => context)
            .Select(static (context, token) => {
                token.ThrowIfCancellationRequested();
                return (classSymbol: context.TargetSymbol.ContainingType, target: context.TargetSymbol);
            })
            .Collect()
            .SelectMany(static (targets, token) => {
                token.ThrowIfCancellationRequested();
                return targets.GroupBy<(INamedTypeSymbol classSymbol, ISymbol target), INamedTypeSymbol, Target>(elem => elem.classSymbol,
                                                                                                                 (key, elems) => new Target(key, elems.Select(e => e.target)),
                                                                                                                 SymbolEqualityComparer.Default);
            });

        context.RegisterSourceOutput(source, Emit);
        context.RegisterSourceOutput(source.Collect(), CreateConfigSystem);

        var configProviders = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, token) => node.IsKind(SyntaxKind.ClassDeclaration),
            static (context, token) => (INamedTypeSymbol)context.SemanticModel.GetDeclaredSymbol(context.Node))
            .Where(sym => sym is not null)
            .Where(static (symbol) =>
            {
                var nameOnlyDisplayFormat = new SymbolDisplayFormat(); // display name only

                foreach (INamedTypeSymbol _interface in ((INamedTypeSymbol)symbol).Interfaces)
                {
                    if (_interface.Name == "IConfigProvider")
                    {
                        return true;
                    }
                }
                return false;
            })
            // .Select(static context => context.);
        ;

    }

    private static void Emit(SourceProductionContext context, Target target)
    {
        string fullTypeName = target.ClassSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", "")
            .Replace("<", "_")
            .Replace(">", "_");;
        var ns = target.ClassSymbol.ContainingNamespace;
        bool isGlobalNamespace = ns.IsGlobalNamespace;

        var configStructConstructor = $$"""
            public Config({{string.Join(", ", target.ConfigurableMembers.Select(m => $"{((IFieldSymbol)m).Type} __{m.Name}"))}})
            {
                {{string.Join("\n", target.ConfigurableMembers.Select(m => $"{m.Name} = __{m.Name};"))}}
            }
        """;

        string contents = $$"""
                          // <auto-generated/>
                          using UnityEngine;
                          #nullable enable

                          {{(isGlobalNamespace ? "" : $"namespace {ns} {{")}}
                          partial class {{target.ClassSymbol.Name}}
                          {
                              public struct Config
                              {
                                  {{string.Join("\n", target.ConfigurableMembers.Select(m => $"public readonly {((IFieldSymbol)m).Type} {m.Name};"))}}

                                  {{configStructConstructor}}
                              }

                              public void Configure(Config config)
                              {
                                  {{string.Join("\n", target.ConfigurableMembers.Select(m => $"{m.Name} = config.{m.Name};"))}}
                              }
                          }
                          {{(isGlobalNamespace ? "" : "}")}}

                          """;

        context.AddSource($"{fullTypeName}.ConfigurablesGenerator.g.cs", contents);
    }

    private static void CreateConfigSystem(SourceProductionContext context, ImmutableArray<Target> targets)
    {
        var configSystemBase = $$"""
            using UnityEngine;

        namespace Configurables
        {
            public partial class ConfigSystem
            {
                public struct Config
                {
                    {{string.Join("\n", targets.Select(t => $"public {t.ClassSymbol.Name}.Config {t.ClassSymbol.Name};"))}}                   
                }

                [SerializeReference] private IConfigProvider m_ConfigProvider;
                {{string.Join("\n", targets.Select(t => $"[SerializeField] private {t.ClassSymbol.Name} m_{t.ClassSymbol.Name};"))}}

                public void Configure()
                {
                    Config config = m_ConfigProvider.GetConfig();
                    {{string.Join("\n", targets.Select(t => $"m_{t.ClassSymbol.Name}.Configure(config.{t.ClassSymbol.Name});"))}}
                }
            }
        }
        """;
        context.AddSource("ConfigSystem.g.cs", configSystemBase);
    }
}
